/** Вкладка «Волна»: запуск, подборки и экран играющей волны. */
@Composable
fun WaveTab(model: AppViewModel, player: PlayerController?, onOpenPlayer: () -> Unit) {
    val queue by QueueHolder.state.collectAsStateWithLifecycle()
    if (queue.isWave && queue.currentTrack() != null) {
        WavePlaying(queue, player, model, onOpenPlayer)
    } else {
        WaveIdle(model, player)
    }
}

@Composable
private fun WaveIdle(model: AppViewModel, player: PlayerController?) {
    val starting by model.waveStarting.collectAsStateWithLifecycle()
    val generated by model.generated.collectAsStateWithLifecycle()
    val error by model.waveError.collectAsStateWithLifecycle()

    Box(Modifier.fillMaxSize()) {
        Glow(
            360.dp,
            Modifier.align(Alignment.TopCenter).offset(y = (-60).dp),
            alpha = 0.5f,
        )
        Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(top = 12.dp, bottom = 16.dp)) {
            PlText("Моя волна", PlType.display, modifier = Modifier.padding(horizontal = 20.dp))
            Spacer(Modifier.height(24.dp))
            Box(Modifier.fillMaxWidth().height(290.dp), contentAlignment = Alignment.Center) {
                Canvas(Modifier.size(272.dp)) {
                    val stroke = Stroke(1.dp.toPx())
                    drawCircle(Color.White.copy(alpha = 0.06f), radius = 136.dp.toPx(), style = stroke)
                    drawCircle(Color.White.copy(alpha = 0.10f), radius = 104.dp.toPx(), style = stroke)
                }
                Box(Modifier.size(152.dp).background(Pl.accent.copy(alpha = 0.22f), CircleShape))
                Box(
                    Modifier
                        .size(100.dp)
                        .clip(CircleShape)
                        .background(Pl.accent, CircleShape)
                        .clickable(enabled = !starting) { model.startWave(player) },
                    contentAlignment = Alignment.Center,
                ) {
                    if (starting) {
                        CircularProgressIndicator(
                            Modifier.size(36.dp),
                            color = Pl.onAccent,
                            strokeWidth = 3.dp,
                        )
                    } else {
                        PlIcon(R.drawable.ic_play_filled, 42.dp, Pl.onAccent)
                    }
                }
            }
            Spacer(Modifier.height(12.dp))
            PlText(
                "Бесконечный поток музыки под ваш вкус",
                PlType.secondary,
                Pl.text2,
                Modifier.fillMaxWidth().padding(horizontal = 24.dp),
                textAlign = TextAlign.Center,
            )
            error?.let {
                Spacer(Modifier.height(12.dp))
                PlText(
                    it,
                    PlType.secondary,
                    Pl.error,
                    Modifier.fillMaxWidth().padding(horizontal = 24.dp),
                    textAlign = TextAlign.Center,
                )
            }
            if (generated.isNotEmpty()) {
                Spacer(Modifier.height(32.dp))
                PlText("Собираем для вас", PlType.title, modifier = Modifier.padding(horizontal = 20.dp))
                Spacer(Modifier.height(14.dp))
                LazyRow(
                    horizontalArrangement = Arrangement.spacedBy(12.dp),
                    contentPadding = PaddingValues(horizontal = 20.dp),
                ) {
                    items(generated, key = { it.kind }) { playlist ->
                        PlaylistCard(playlist) { model.playPlaylist(player, playlist) }
                    }
                }
            }
        }
    }
}

/** Карточка подборки: обложка 132, название и число треков. */
@Composable
private fun PlaylistCard(playlist: GeneratedPlaylist, onPlay: () -> Unit) {
    Column(
        Modifier.width(132.dp).clickable(onClick = onPlay),
        verticalArrangement = Arrangement.spacedBy(2.dp),
    ) {
        Cover(playlist.coverUrl(), playlist.kind.toString(), 132.dp, 16.dp)
        Spacer(Modifier.height(6.dp))
        PlText(playlist.title, PlType.secondaryStrong, maxLines = 1)
        PlText(tracksCount(playlist.trackCount), PlType.caption, Pl.text3, maxLines = 1)
    }
}

@Composable
private fun WavePlaying(
    queue: QueueHolder.State,
    player: PlayerController?,
    model: AppViewModel,
    onOpenPlayer: () -> Unit,
) {
    val track = queue.currentTrack() ?: return
    val tint = rememberTint(queue, track)
    val playing = player?.isPlaying?.collectAsStateWithLifecycle()?.value ?: false
    val liked by QueueHolder.likedIds.collectAsStateWithLifecycle()
    val progress by rememberProgress(player, track)
    var preview by remember { mutableStateOf<Float?>(null) }
    val next = queue.tracks.getOrNull(queue.current + 1)

    Box(Modifier.fillMaxSize()) {
        Glow(
            420.dp,
            Modifier.align(Alignment.TopCenter).offset(y = (-60).dp),
            color = tint,
            alpha = 0.55f,
        )
        Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(top = 12.dp, bottom = 16.dp)) {
            PlText("Моя волна", PlType.display, modifier = Modifier.padding(horizontal = 20.dp))
            Spacer(Modifier.height(24.dp))
            Box(Modifier.fillMaxWidth(), contentAlignment = Alignment.Center) {
                Box(
                    Modifier
                        .size(232.dp)
                        .clip(RoundedCornerShape(24.dp))
                        .clickable(onClick = onOpenPlayer),
                ) {
                    Cover(track.coverUrl("600x600"), track.id, 232.dp, 24.dp)
                    Box(
                        Modifier
                            .size(232.dp)
                            .border(2.dp, tint, RoundedCornerShape(24.dp)),
                    )
                }
            }
            Spacer(Modifier.height(24.dp))
            PlText(
                track.title,
                PlType.title,
                modifier = Modifier.fillMaxWidth().padding(horizontal = 24.dp),
                textAlign = TextAlign.Center,
                maxLines = 2,
            )
            Spacer(Modifier.height(2.dp))
            PlText(
                track.artistNames,
                PlType.body,
                Pl.text2,
                Modifier.fillMaxWidth().padding(horizontal = 24.dp),
                textAlign = TextAlign.Center,
                maxLines = 1,
            )
            Spacer(Modifier.height(14.dp))
            Column(Modifier.padding(horizontal = 32.dp)) {
                SeekBar(
                    fraction = progress.fraction,
                    color = tint,
                    onSeek = { f ->
                        if (progress.durationMs > 0) player?.seekTo((f * progress.durationMs).toLong())
                    },
                    onPreview = { preview = it },
                )
                val shown = preview?.let { (it * progress.durationMs).toLong() } ?: progress.positionMs
                TimeRow(shown, progress.durationMs, Pl.text2)
            }
            Spacer(Modifier.height(12.dp))
            Row(
                Modifier.fillMaxWidth().padding(horizontal = 36.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Box(Modifier.size(44.dp).clip(CircleShape).clickable { player?.previous() }, Alignment.Center) {
                    PlIcon(R.drawable.ic_previous_filled, 32.dp, Pl.text)
                }
                PlayButton(76.dp, playing, onClick = { player?.toggle() }, color = tint, onColor = onColorFor(tint))
                Box(Modifier.size(44.dp).clip(CircleShape).clickable { player?.next() }, Alignment.Center) {
                    PlIcon(R.drawable.ic_next_filled, 32.dp, Pl.text)
                }
                HeartButton(liked.contains(track.id), { model.toggleLike(track) }, 26.dp)
            }
            next?.let {
                Spacer(Modifier.height(20.dp))
                PlText(
                    "Далее: ${it.title} — ${it.artistNames}",
                    PlType.caption,
                    Pl.text3,
                    Modifier.fillMaxWidth().padding(horizontal = 24.dp),
                    textAlign = TextAlign.Center,
                    maxLines = 1,
                )
            }
        }
    }
}
